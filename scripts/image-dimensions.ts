// Measures every image artifact served by the given origins and prints SQL that records each
// image's pixel size in its artifact data. Rows that already have a size are left alone.
//
//   bun scripts/image-dimensions.ts http://localhost:5173 https://erhathaway.com > drizzle/<migration>.sql
//
// Images are matched by URL rather than artifact id, since ids differ between databases. Only
// published artifacts are visible without signing in, so unpublished ones are measured at render.
import { chromium } from 'playwright';

const origins = process.argv.slice(2);
if (origins.length === 0) {
	console.error('Usage: bun scripts/image-dimensions.ts <origin> [origin...]');
	process.exit(1);
}

type ImageArtifact = { schema: string; dataBlob: { imageUrl?: unknown; width?: unknown } };

// Image URL → the first origin it was seen on.
const urls = new Map<string, string>();
for (const origin of origins) {
	const projects = (await (await fetch(`${origin}/api/projects`)).json()) as { id: number }[];
	for (const project of projects) {
		const artifacts = (await (await fetch(`${origin}/api/projects/${project.id}/artifacts`)).json()) as ImageArtifact[];
		for (const artifact of artifacts) {
			const url = artifact.dataBlob?.imageUrl;
			if (artifact.schema !== 'image-v1' || typeof url !== 'string' || typeof artifact.dataBlob.width === 'number') continue;
			if (!urls.has(url)) urls.set(url, origin);
		}
	}
}
console.error(`Measuring ${urls.size} images`);

// Playwright's own browser needs a download; an installed Chrome works just as well for this.
const browser = await chromium.launch().catch(() => chromium.launch({ channel: 'chrome' }));
const page = await browser.newPage();

const measure = (src: string) =>
	page.evaluate(
		(src) =>
			new Promise<[number, number] | null>((resolve) => {
				const img = new Image();
				img.onload = () => resolve(img.naturalWidth > 0 ? [img.naturalWidth, img.naturalHeight] : null);
				img.onerror = () => resolve(null);
				img.src = src;
			}),
		src
	);
const sizes = new Map<string, [number, number] | null>();
const queue = [...urls.entries()];
await Promise.all(
	Array.from({ length: 6 }, async () => {
		for (let next = queue.shift(); next; next = queue.shift()) {
			const [url, origin] = next;
			// A dev server restarting mid-run fails a few loads, so each image gets a few tries.
			let size: [number, number] | null = null;
			for (let attempt = 0; attempt < 3 && !size; attempt++) {
				if (attempt > 0) await new Promise((r) => setTimeout(r, 3000 * attempt));
				size = await measure(new URL(url, origin).href);
			}
			sizes.set(url, size);
			if (!size) console.error(`Could not measure ${origin}${url}`);
		}
	})
);
await browser.close();

const statements: string[] = [];
for (const url of [...sizes.keys()].sort()) {
	const size = sizes.get(url);
	if (!size) {
		statements.push(`-- could not measure ${url}`);
		continue;
	}
	const literal = `'${url.replace(/'/g, "''")}'`;
	statements.push(
		`UPDATE \`project_artifacts\` SET \`data_blob\` = json_set(\`data_blob\`, '$.width', ${size[0]}, '$.height', ${size[1]})\n` +
			`WHERE \`schema\` = 'image-v1' AND json_extract(\`data_blob\`, '$.imageUrl') = ${literal} AND json_type(\`data_blob\`, '$.width') IS NULL;`
	);
}
console.log('-- Record each image artifact\'s pixel size. Generated by scripts/image-dimensions.ts.');
console.log(statements.join('\n--> statement-breakpoint\n'));
console.error(`Measured ${[...sizes.values()].filter(Boolean).length} of ${sizes.size}`);
